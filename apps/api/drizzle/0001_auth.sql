-- Maximum session duration: activity extends expires_at (inactivity timeout), but never past 7 days from sign-in.
CREATE FUNCTION "cap_session_expiry"() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	NEW.expires_at := LEAST(NEW.expires_at, NEW.created_at + interval '7 days');
	RETURN NEW;
END;
